import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { withChromiumOracle, ORACLE_BROWSER_VERSION } from './chromium-oracle.mjs';

const mode = process.argv[2];
if (!['--write', '--check'].includes(mode) || process.argv.length !== 3) {
  throw new Error('Usage: node unicode-uppercase-table.mjs --write|--check');
}
const mappings = await withChromiumOracle(page => page.evaluate(() => {
  const changed = [];
  for (let codePoint = 0; codePoint <= 0x10ffff; codePoint++) {
    if (codePoint >= 0xd800 && codePoint <= 0xdfff) continue;
    const input = String.fromCodePoint(codePoint);
    const uppercase = input.toUpperCase();
    if (uppercase !== input) changed.push({ codePoint, uppercase });
  }
  return changed;
}));
const rows = mappings.map(({ codePoint, uppercase }) =>
  `${codePoint.toString(16)}=${[...uppercase].map(ch => ch.codePointAt(0).toString(16)).join(',')};`);
const mappingSha256 = createHash('sha256').update(rows.join('')).digest('hex');
const chunks = [];
for (let index = 0; index < rows.length; index += 20) chunks.push(rows.slice(index, index + 20).join(''));
const source = [
  '// Generated by chrome-extension/scripts/unicode-uppercase-table.mjs; do not hand edit.',
  `// Oracle: repo E2E Chromium ${ORACLE_BROWSER_VERSION}; all scalar code points checked.`,
  'package dev.passchef.mobile.recipe', '', 'internal object UnicodeUppercaseData {',
  `    const val browserVersion = "${ORACLE_BROWSER_VERSION}"`,
  `    const val mappingSha256 = "${mappingSha256}"`,
  '    val chunks = arrayOf(', ...chunks.map(chunk => `        "${chunk}",`), '    )', '}', '',
].join('\n');
const fixture = JSON.stringify({ _warning: 'SYNTHETIC TEST DATA ONLY', browserVersion: ORACLE_BROWSER_VERSION, mappingSha256,
  scalarCount: 0x110000 - 0x800, mappings }, null, 2) + '\n';
const outputs = [
  [new URL('../../shared/src/commonMain/kotlin/dev/passchef/mobile/recipe/UnicodeUppercaseData.kt', import.meta.url), source],
  [new URL('../../shared/src/jvmTest/resources/unicode-uppercase-reference.json', import.meta.url), fixture],
];
for (const [path, expected] of outputs) {
  if (mode === '--write') {
    await mkdir(new URL('.', path), { recursive: true });
    await writeFile(path, expected);
  } else if (await readFile(path, 'utf8') !== expected) {
    throw new Error(`Uppercase oracle differs: ${path.pathname}; investigate before explicitly regenerating`);
  }
}
console.log(`${mode === '--check' ? 'Verified' : 'Recorded'} ${mappings.length} changed mappings; ` +
  `all ${0x110000 - 0x800} scalar code points checked against Chromium ${ORACLE_BROWSER_VERSION}; SHA256 ${mappingSha256}.`);
